import math
x=5.7
y=3

print("Number:", x)
print("Square:", math.sqrt(x))
print("Power:", math.pow(x, y))
print("Ceiling:", math.ceil(x))
print("Floor:", math.floor(x))
print("Absolute:", math.fabs(-x))
"""-x becuase it is negative number and fabs is return positive value."""

print("Absolute:", math.fabs(y))
"""y is positive number and fabs is return positive value."""

print("Factorial:", math.factorial(y))
print("GCD of 12 & 8:", math.gcd(12,8))
"""GCD is greatest common divisor."""

print("Nature log of 10:", math.log(10))
print("Log base 10 of 100:", math.log10(100))
print("Sing of 30 degree:",math.sin(30))
print("Cosine of 30 degree:",math.cos(30))
print("Tangent of 30 degree:",math.tan(30))
print("Pi value:", math.pi)
print("Euler's number:", math.e)
